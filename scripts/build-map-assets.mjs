#!/usr/bin/env node
// Copies MapLibre GL JS into a module the app can inline into its map web
// view, so the map needs no network and no file access. Runs on npm install.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..', 'app');
const require = createRequire(join(app, 'package.json'));
const dist = dirname(require.resolve('maplibre-gl/dist/maplibre-gl.js'));
const out = join(app, 'src/map/generated');
mkdirSync(out, { recursive: true });
const js = readFileSync(join(dist, 'maplibre-gl.js'), 'utf8');
const css = readFileSync(join(dist, 'maplibre-gl.css'), 'utf8');
writeFileSync(join(out, 'maplibre.js'), `// Generated by scripts/build-map-assets.mjs. Do not edit.\nmodule.exports = ${JSON.stringify({ js, css })};\n`);
console.log(`maplibre-gl inlined: ${(js.length / 1e6).toFixed(1)} MB -> app/src/map/generated/maplibre.js`);

#!/usr/bin/env node
// Bakes OpenStreetMap vector tiles for the destination into the app, so the
// map works with Wi-Fi off. Run once while online:
//
//   node scripts/build-tiles.mjs                      # latest Protomaps daily build
//   node scripts/build-tiles.mjs --source seville.pmtiles   # a local extract
//   node scripts/build-tiles.mjs --maxzoom 15 --dest seville
//
// It reads only the tiles inside the destination's bounds (HTTP range
// requests), and writes app/src/map/generated/tiles.js, which is gitignored.
// Data © OpenStreetMap contributors, via Protomaps (https://protomaps.com).
import { readFileSync, writeFileSync, openSync, readSync, fstatSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..', 'app');
const require = createRequire(join(app, 'package.json'));
const { PMTiles, FetchSource } = require('pmtiles');

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith('--') ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
);
const destId = args.dest ?? 'seville';
const minzoom = Number(args.minzoom ?? 11);
const maxzoom = Number(args.maxzoom ?? 15);
const dest = JSON.parse(readFileSync(join(app, `src/pack/${destId}/destination.json`), 'utf8'));
const [west, south, east, north] = dest.bounds;

function defaultSource() {
  const d = new Date(Date.now() - 2 * 86_400_000);
  return `https://build.protomaps.com/${d.toISOString().slice(0, 10).replace(/-/g, '')}.pmtiles`;
}

class FileSource {
  constructor(path) {
    this.path = path;
    this.fd = openSync(path, 'r');
    this.size = fstatSync(this.fd).size;
  }
  getKey() {
    return this.path;
  }
  async getBytes(offset, length) {
    const buf = Buffer.alloc(Math.min(length, this.size - offset));
    readSync(this.fd, buf, 0, buf.length, offset);
    return { data: buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.length) };
  }
}

const lon2x = (lon, z) => Math.floor(((lon + 180) / 360) * 2 ** z);
const lat2y = (lat, z) => {
  const r = (lat * Math.PI) / 180;
  return Math.floor(((1 - Math.log(Math.tan(r) + 1 / Math.cos(r)) / Math.PI) / 2) * 2 ** z);
};

const source = args.source ?? defaultSource();
const pm = new PMTiles(/^https?:/.test(source) ? new FetchSource(source) : new FileSource(source));
console.log(`Reading ${source}`);
const header = await pm.getHeader();
const tiles = {};
let bytes = 0;
for (let z = minzoom; z <= Math.min(maxzoom, header.maxZoom); z++) {
  const [x0, x1, y0, y1] = [lon2x(west, z), lon2x(east, z), lat2y(north, z), lat2y(south, z)];
  for (let x = x0; x <= x1; x++) {
    for (let y = y0; y <= y1; y++) {
      const t = await pm.getZxy(z, x, y);
      if (!t) continue;
      tiles[`${z}/${x}/${y}`] = Buffer.from(t.data).toString('base64');
      bytes += t.data.byteLength;
    }
  }
  console.log(`z${z}: ${Object.keys(tiles).length} tiles so far, ${(bytes / 1e6).toFixed(1)} MB`);
}
mkdirSync(join(app, 'src/map/generated'), { recursive: true });
writeFileSync(
  join(app, 'src/map/generated/tiles.js'),
  `// Generated by scripts/build-tiles.mjs from ${source}. Do not edit or commit.\nmodule.exports = ${JSON.stringify({ minzoom, maxzoom: Math.min(maxzoom, header.maxZoom), tiles })};\n`,
);
console.log(`Wrote ${Object.keys(tiles).length} tiles to app/src/map/generated/tiles.js. Restart Metro with --reset-cache.`);
